package dimblend.experience.chassis;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import net.minecraft.core.BlockPos;
import org.junit.jupiter.api.Test;

/**
 * Which blocks may stand inside a chassis footprint before the car is built.
 *
 * <p>A user reported on 2026-11-01 that a fresh depot built no chassis at all. The site
 * log showed {@code built=0 assembled=0 attempts=8} — the build step never got past its
 * clear check. The blocker was one {@code create:fake_track} block at the east end of the
 * siding: Create writes fake tracks along a bezier connection
 * ({@code TrackBlockEntity#manageFakeTracksAlong}), and a fake track is a plain
 * {@code Block}, not a {@code TrackBlock}, so the old check treated it as an obstruction.
 */
class ChassisSiteClearanceTest {
    private static final BlockPos CENTRE = new BlockPos(8192, 65, 10);

    @Test
    void aRealTrackIsNotAnObstruction() {
        assertTrue(ChassisSite.isIgnorable("railways:track_birch_wide", true, false),
                "the siding's own rails must not block the car");
    }

    /**
     * Create's fake track marks where a bezier connection runs. It is generated by the
     * curve builder, so the depot cannot avoid it, and it carries no collision of its own.
     */
    @Test
    void aCreateFakeTrackIsNotAnObstruction() {
        assertTrue(ChassisSite.isIgnorable("create:fake_track", false, false),
                "fake tracks are curve markers, not terrain");
    }

    @Test
    void ordinaryBlocksStillBlock() {
        assertFalse(ChassisSite.isIgnorable("minecraft:stone", false, false));
        assertFalse(ChassisSite.isIgnorable("minecraft:cobblestone", false, false));
        assertFalse(ChassisSite.isIgnorable("dimblend_blocks:creative_copycat_panel", false, false));
    }

    @Test
    void airIsNotAnObstruction() {
        assertTrue(ChassisSite.isIgnorable("minecraft:air", false, false));
        assertTrue(ChassisSite.isIgnorable("minecraft:cave_air", false, false));
    }

    @Test
    void aPlacedBlueprintBlockIsNotAnObstruction() {
        assertTrue(ChassisSite.isIgnorable("minecraft:stone", false, true),
                "our own built cells are expected, not obstacles");
    }
}