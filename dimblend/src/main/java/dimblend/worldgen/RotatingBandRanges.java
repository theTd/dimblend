package dimblend.worldgen;

import java.util.ArrayList;
import java.util.List;
import java.util.function.IntUnaryOperator;

/**
 * Splits an inclusive chunk-X range into contiguous runs that share one rotating band delegate.
 *
 * <p>Band boundaries are block-X multiples of {@code bandSize} and {@code bandSize} is always a
 * multiple of 16 (enforced by {@link RotatingChunkGenerator}), so every chunk belongs entirely to
 * one band. Adjacent bands that resolve to the same delegate are merged into one range. Pure
 * integer geometry, no runtime/server state, so the chunk→band→delegate mapping can be resolved
 * once on the server thread and handed to another thread.
 */
public final class RotatingBandRanges {
    private RotatingBandRanges() {
    }

    /**
     * @param minChunkX inclusive first chunk X
     * @param maxChunkX inclusive last chunk X
     * @param bandSize  band width in blocks (positive multiple of 16)
     * @param delegateIndexForBlockX resolves a block X to the delegate index that generates it
     */
    public static List<Range> split(
            int minChunkX,
            int maxChunkX,
            int bandSize,
            IntUnaryOperator delegateIndexForBlockX) {
        if (bandSize <= 0 || bandSize % 16 != 0) {
            throw new IllegalArgumentException("Band size must be a positive multiple of 16: " + bandSize);
        }
        if (minChunkX > maxChunkX) {
            throw new IllegalArgumentException("Inverted chunk range: " + minChunkX + ".." + maxChunkX);
        }
        int bandChunks = bandSize / 16;
        int firstRegion = Math.floorDiv(minChunkX, bandChunks);
        int lastRegion = Math.floorDiv(maxChunkX, bandChunks);
        List<Range> ranges = new ArrayList<>(lastRegion - firstRegion + 1);
        Range previous = null;
        for (int region = firstRegion; region <= lastRegion; region++) {
            int runMin = Math.max(minChunkX, Math.multiplyExact(region, bandChunks));
            int runMax = Math.min(maxChunkX, Math.multiplyExact(region + 1, bandChunks) - 1);
            int delegateIndex = delegateIndexForBlockX.applyAsInt(Math.multiplyExact(region, bandSize));
            if (previous != null && previous.delegateIndex() == delegateIndex && previous.maxChunkX() + 1 == runMin) {
                previous = new Range(delegateIndex, previous.minChunkX(), runMax);
                ranges.set(ranges.size() - 1, previous);
            } else {
                previous = new Range(delegateIndex, runMin, runMax);
                ranges.add(previous);
            }
        }
        return List.copyOf(ranges);
    }

    /** A contiguous chunk-X run generated by one band delegate. */
    public record Range(int delegateIndex, int minChunkX, int maxChunkX) {
        public Range {
            if (delegateIndex < 0) {
                throw new IllegalArgumentException("Negative delegate index: " + delegateIndex);
            }
            if (minChunkX > maxChunkX) {
                throw new IllegalArgumentException("Inverted chunk range: " + minChunkX + ".." + maxChunkX);
            }
        }
    }
}
