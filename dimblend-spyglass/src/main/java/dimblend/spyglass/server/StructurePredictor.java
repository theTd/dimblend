package dimblend.spyglass.server;

import dimblend.spyglass.DimBlendSpyglass;
import dimblend.spyglass.structure.OutlineBox;
import dimblend.spyglass.structure.SpyglassDistance;
import dimblend.spyglass.structure.StructureKey;
import dimblend.spyglass.structure.StructureOutline;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import javax.annotation.Nullable;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.chunk.ProtoChunk;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.level.levelgen.structure.Structure;
import net.minecraft.world.level.levelgen.structure.StructurePiece;
import net.minecraft.world.level.levelgen.structure.StructureStart;

/**
 * Replays world generation for the chunks that have no saved structure data, so structures in regions
 * the player has never visited can be marked.
 *
 * <p><b>What this can and cannot produce.</b> Structure placement is a pure function of the level seed
 * and the datapack: {@code Structure.generate} picks a start position from the structure's height
 * provider and assembles a jigsaw from templates, returning a {@link StructureStart} whose pieces are
 * {@link BoundingBox}es ({@code Structure.java:91-100}). None of that reads the world; it is the same
 * path {@code /locate} uses ({@code StructureCheck.java:97-110}). The <b>blocks</b> of a structure,
 * however, exist only once {@code StructureStart.placeInChunk} has written them into a
 * {@code WorldGenLevel} ({@code StructureStart.java:80-96}), and biome decoration reads the real
 * biomes of the surrounding chunks. This class therefore marks where a structure is and how large it
 * is, and deliberately produces no block shape.
 *
 * <p><b>How it stays truthful.</b> It never generates on the live level and never loads a chunk: it
 * calls the dimension's own {@code ChunkGenerator.createStructures} on a throwaway {@link ProtoChunk}
 * (see {@link PredictionContext}), which replays band routing, structure-set weighting and the
 * no-structure zones instead of re-implementing them. It is only ever asked about candidates the
 * region scan found no saved start for, so a prediction can never contradict saved world data.
 *
 * <p><b>Why the budget and the cache exist.</b> A jigsaw assembly costs one to two orders of magnitude
 * more than reading a region header, and a scan window is roughly 200×200 chunks. Predicting every
 * absent candidate at once would stall the scan executor, so each scan spends a fixed budget on the
 * <b>nearest</b> chunks and results are cached per chunk: a fresh world fills in over successive
 * refreshes, while a visited area costs nothing. The cache never needs explicit invalidation — once a
 * chunk has a saved start it is no longer absent, so it is not looked up again.
 *
 * <p>Thread-confined to the scan executor; the map is synchronized only so {@link #clear()} from the
 * session teardown cannot race a scan.
 */
final class StructurePredictor {
    /**
     * Chunks one scan may generate. Deliberately small: the scan executor is shared with the region
     * reads and the shape extraction, and the cache carries results forward, so a small budget only
     * delays how quickly distant unvisited structures appear.
     */
    static final int MAX_CHUNKS_PER_SCAN = 24;
    /** Bounded so a long session crossing a large unvisited area cannot grow without limit. */
    static final int MAX_CACHED_CHUNKS = 2048;
    /**
     * A structure's union bounds can reach well past its start chunk (mansions, large modded
     * dungeons). A start chunk beyond the outer snapshot ring by more than this cannot produce a
     * visible outline, so generating it would be wasted work.
     */
    static final double START_CHUNK_MARGIN_BLOCKS = 128.0;

    /** Per-chunk prediction: the outlines of the requested structures that generated there. */
    private final Map<ChunkKey, Map<ResourceLocation, StructureOutline>> cache = new LinkedHashMap<>();

    /**
     * @param outlines        predicted outlines for absent candidates, nearest chunk first
     * @param generatedChunks chunks actually generated by this call
     * @param cacheHits       chunks answered from the cache instead
     * @param skippedChunks   eligible chunks the per-scan budget could not afford
     * @param failedChunks    chunks whose generation threw; they stay unshown
     */
    record Prediction(
            List<StructureOutline> outlines,
            int generatedChunks,
            int cacheHits,
            int skippedChunks,
            int failedChunks) {
        Prediction {
            outlines = List.copyOf(outlines);
        }

        static Prediction empty() {
            return new Prediction(List.of(), 0, 0, 0, 0);
        }
    }

    /**
     * Predicts the absent candidates within reach of the player, spending at most
     * {@link #MAX_CHUNKS_PER_SCAN} generations on the nearest chunks not already cached.
     *
     * <p>Must run on the scan executor, after the generator's structure states were prepared on the
     * server thread (see {@link StructureCandidates#bandsFor}).
     */
    Prediction predict(
            PredictionContext context,
            List<StructureCandidate> absent,
            double playerX,
            double playerZ) {
        if (absent.isEmpty() || !context.shouldGenerateStructures()) {
            // A level created without structure generation will never contain these structures;
            // predicting would invent buildings the world does not have.
            return Prediction.empty();
        }

        // Group by chunk: createStructures is a per-chunk call that resolves every structure set the
        // chunk belongs to in one go, so asking once per candidate would repeat the assembly.
        Map<Long, List<StructureCandidate>> byChunk = new LinkedHashMap<>();
        for (StructureCandidate candidate : absent) {
            byChunk.computeIfAbsent(candidate.chunkKey(), key -> new ArrayList<>()).add(candidate);
        }

        // Only chunks close enough to place a visible outline are worth generating. The outer display
        // edge plus the snapshot pad plus the piece extent gives that reach.
        double reachBlocks = SpyglassDistance.MAX_BLOCKS
                + SpyglassRefreshPolicy.SNAPSHOT_PAD_BLOCKS
                + START_CHUNK_MARGIN_BLOCKS;
        List<Map.Entry<Long, List<StructureCandidate>>> ordered = new ArrayList<>(byChunk.entrySet());
        ordered.sort(Comparator.comparingDouble(entry -> chunkDistance(playerX, playerZ, entry.getKey())));

        List<StructureOutline> outlines = new ArrayList<>();
        int generated = 0;
        int hits = 0;
        int skipped = 0;
        int failed = 0;
        for (Map.Entry<Long, List<StructureCandidate>> entry : ordered) {
            if (chunkDistance(playerX, playerZ, entry.getKey()) > reachBlocks) {
                continue;
            }
            ChunkKey key = new ChunkKey(context.dimension(), entry.getKey());
            Map<ResourceLocation, StructureOutline> generatedHere = this.cache.get(key);
            if (generatedHere != null) {
                hits++;
            } else {
                if (generated >= MAX_CHUNKS_PER_SCAN) {
                    skipped++;
                    continue;
                }
                generated++;
                generatedHere = generate(context, entry.getKey(), entry.getValue());
                if (generatedHere == null) {
                    failed++;
                    continue;
                }
                put(key, generatedHere);
            }
            for (StructureCandidate candidate : entry.getValue()) {
                StructureOutline outline = generatedHere.get(candidate.id());
                if (outline != null) {
                    outlines.add(outline);
                }
            }
        }
        return new Prediction(outlines, generated, hits, skipped, failed);
    }

    /** Frees every cached chunk; called when the session ends. */
    synchronized void clear() {
        this.cache.clear();
    }

    /**
     * Runs one chunk's structure placement on a throwaway chunk and returns the outlines it produced,
     * or {@code null} when generation failed — that chunk stays unshown rather than guessed at.
     */
    @Nullable
    private static Map<ResourceLocation, StructureOutline> generate(
            PredictionContext context, long chunkKey, List<StructureCandidate> candidates) {
        int chunkX = ChunkPos.getX(chunkKey);
        int chunkZ = ChunkPos.getZ(chunkKey);
        ProtoChunk chunk;
        try {
            chunk = context.createStructures(new ChunkPos(chunkX, chunkZ));
        } catch (RuntimeException exception) {
            // A datapack that fails to assemble must not kill the whole scan; one throttled warning
            // per dimension reports it (see SpyglassServerService#reportPredictionFailures).
            DimBlendSpyglass.LOGGER.debug(
                    "Spyglass structure prediction failed for chunk {},{}", chunkX, chunkZ, exception);
            return null;
        }
        Set<ResourceLocation> wanted = new LinkedHashSet<>();
        for (StructureCandidate candidate : candidates) {
            wanted.add(candidate.id());
        }
        Map<ResourceLocation, StructureOutline> found = new LinkedHashMap<>();
        for (Map.Entry<Structure, StructureStart> entry : chunk.getAllStarts().entrySet()) {
            if (!entry.getValue().isValid()) {
                continue;
            }
            ResourceLocation id = context.idOf(entry.getKey());
            if (id == null || !wanted.contains(id)) {
                continue;
            }
            List<OutlineBox> pieces = piecesOf(entry.getValue());
            if (pieces.isEmpty()) {
                continue;
            }
            found.put(id, StructureOutline.predicted(new StructureKey(id, chunkX, chunkZ), pieces));
        }
        return found;
    }

    /**
     * Piece boxes exactly as a saved start stores them, so a predicted outline and a read outline of
     * the same structure are indistinguishable to the limiter and the client.
     */
    private static List<OutlineBox> piecesOf(StructureStart start) {
        List<StructurePiece> pieces = start.getPieces();
        List<OutlineBox> boxes = new ArrayList<>(pieces.size());
        for (StructurePiece piece : pieces) {
            BoundingBox box = piece.getBoundingBox();
            try {
                boxes.add(new OutlineBox(
                        box.minX(), box.minY(), box.minZ(),
                        box.maxX(), box.maxY(), box.maxZ()));
            } catch (IllegalArgumentException outsideWorld) {
                // Same rule as the NBT read path: a box outside the representable world is dropped
                // instead of failing the structure.
            }
        }
        return boxes;
    }

    private synchronized void put(ChunkKey key, Map<ResourceLocation, StructureOutline> value) {
        if (this.cache.size() >= MAX_CACHED_CHUNKS) {
            // Oldest insertion first: the scan visits nearest-first, so the oldest entry is the
            // farthest from where the player has been.
            Iterator<ChunkKey> iterator = this.cache.keySet().iterator();
            if (iterator.hasNext()) {
                iterator.next();
                iterator.remove();
            }
        }
        this.cache.put(key, value);
    }

    /** Distance from the player to the center of a chunk, in blocks. */
    static double chunkDistance(double playerX, double playerZ, long chunkKey) {
        double centerX = ChunkPos.getX(chunkKey) * 16.0 + 8.0;
        double centerZ = ChunkPos.getZ(chunkKey) * 16.0 + 8.0;
        return Math.hypot(playerX - centerX, playerZ - centerZ);
    }

    private record ChunkKey(ResourceKey<Level> dimension, long chunkKey) {
    }
}